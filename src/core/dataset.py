"""Country bank datasets: loading, validation and lookup.

Bank data is committed to the repository as one JSON file per country in
`data/countries/<ALPHA3>.json`. The files are generated by each country's
refresh module, reviewed as ordinary diffs, and loaded once at startup. A file
that fails validation stops the app from starting rather than serving bad data.
"""

from __future__ import annotations

import datetime
import json
import re
import unicodedata
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from src.countries.profile import CountryProfile
from src.countries.registry import list_country_profiles

DATA_DIR = Path(__file__).resolve().parents[2] / "data" / "countries"

_TOP_LEVEL_KEYS = {"country", "retrieved_on", "sources", "banks"}
_BANK_KEYS = {"id", "name", "type", "identifiers"}
_SLUG_PATTERN = re.compile(r"^[a-z0-9]+(?:-[a-z0-9]+)*$")
_URL_PATTERN = re.compile(r"^https?://[^\s/]+\.[^\s/]+(?:/\S*)?$")


class DatasetError(Exception):
    """Raised when a country data file is missing or does not match its profile."""


@dataclass(frozen=True)
class CountryDataset:
    """One country's validated bank list."""

    profile: CountryProfile
    retrieved_on: str
    sources: tuple[dict[str, str], ...]
    banks: tuple[dict[str, Any], ...]
    banks_by_id: dict[str, dict[str, Any]]


def load_datasets(data_dir: Path = DATA_DIR) -> dict[str, CountryDataset]:
    """Load and validate the data file of every registered country, keyed by alpha-3 code."""
    profiles = list_country_profiles()
    expected_files = {f"{profile.alpha3}.json" for profile in profiles}
    unexpected = sorted(path.name for path in data_dir.glob("*.json") if path.name not in expected_files)
    if unexpected:
        raise DatasetError(f"Data files without a registered country profile: {', '.join(unexpected)}")

    datasets = {}
    for profile in profiles:
        path = data_dir / f"{profile.alpha3}.json"
        try:
            raw = json.loads(path.read_text(encoding="utf-8"))
        except FileNotFoundError as exc:
            raise DatasetError(f"Missing data file for {profile.name}: {path}") from exc
        except json.JSONDecodeError as exc:
            raise DatasetError(f"{path.name} is not valid JSON: {exc}") from exc
        errors = validate_dataset(raw, profile)
        if errors:
            raise DatasetError(f"{path.name} failed validation:\n- " + "\n- ".join(errors))
        banks = tuple(raw["banks"])
        datasets[profile.alpha3] = CountryDataset(
            profile=profile,
            retrieved_on=raw["retrieved_on"],
            sources=tuple(raw["sources"]),
            banks=banks,
            banks_by_id={bank["id"]: bank for bank in banks},
        )
    return datasets


def validate_dataset(raw: Any, profile: CountryProfile) -> list[str]:
    """Return every problem found in one country's raw data, or an empty list."""
    if not isinstance(raw, dict):
        return ["The file must contain a JSON object."]
    errors = []
    if set(raw) != _TOP_LEVEL_KEYS:
        errors.append(f"Top-level keys must be exactly {sorted(_TOP_LEVEL_KEYS)}, found {sorted(raw)}.")
    if raw.get("country") != profile.alpha3:
        errors.append(f"country must be {profile.alpha3!r}, found {raw.get('country')!r}.")
    if not _is_iso_date(raw.get("retrieved_on")):
        errors.append("retrieved_on must be an ISO date such as 2026-01-31.")
    errors.extend(_validate_sources(raw.get("sources")))

    banks = raw.get("banks")
    if not isinstance(banks, list) or not banks:
        errors.append("banks must be a non-empty list.")
        return errors
    seen_ids: set[str] = set()
    for index, bank in enumerate(banks):
        errors.extend(f"banks[{index}]: {error}" for error in _validate_bank(bank, profile, seen_ids))
    if all(isinstance(bank, dict) for bank in banks):
        sort_keys = [bank_sort_key(bank) for bank in banks]
        if sort_keys != sorted(sort_keys):
            errors.append("banks must be sorted by name, then id.")
    return errors


def bank_sort_key(bank: dict[str, Any]) -> tuple[str, str]:
    """Sort banks by name, then id, so regenerated files produce small diffs."""
    return (search_text(str(bank.get("name", ""))), str(bank.get("id", "")))


def search_text(value: str) -> str:
    """Fold case, accents and spacing so `q` searches match the way people type names."""
    decomposed = unicodedata.normalize("NFKD", value)
    without_marks = "".join(char for char in decomposed if not unicodedata.combining(char))
    return " ".join(without_marks.casefold().split())


def _validate_sources(sources: Any) -> list[str]:
    if not isinstance(sources, list) or not sources:
        return ["sources must be a non-empty list."]
    errors = []
    for index, source in enumerate(sources):
        if not isinstance(source, dict) or set(source) != {"name", "url"}:
            errors.append(f"sources[{index}] must have exactly name and url.")
            continue
        if not _is_clean_text(source["name"]):
            errors.append(f"sources[{index}].name must be non-empty trimmed text.")
        if not isinstance(source["url"], str) or not _URL_PATTERN.match(source["url"]):
            errors.append(f"sources[{index}].url must be an http(s) URL.")
    return errors


def _validate_bank(bank: Any, profile: CountryProfile, seen_ids: set[str]) -> list[str]:
    if not isinstance(bank, dict):
        return ["each bank must be a JSON object."]
    errors = []
    missing = _BANK_KEYS - set(bank)
    unknown = set(bank) - _BANK_KEYS
    if missing:
        errors.append(f"missing keys {sorted(missing)}.")
    if unknown:
        errors.append(f"unknown keys {sorted(unknown)}.")

    bank_id = bank.get("id")
    if not isinstance(bank_id, str) or not _SLUG_PATTERN.match(bank_id):
        errors.append(f"id {bank_id!r} must be a lowercase slug such as 'access-bank-plc'.")
    elif bank_id in seen_ids:
        errors.append(f"id {bank_id!r} is used more than once.")
    else:
        seen_ids.add(bank_id)

    if not _is_clean_text(bank.get("name")):
        errors.append("name must be non-empty text without extra spaces.")
    if bank.get("type") not in profile.bank_type_codes():
        errors.append(f"type {bank.get('type')!r} is not one of {profile.bank_type_codes()}.")

    identifiers = bank.get("identifiers")
    if not isinstance(identifiers, dict):
        errors.append("identifiers must be an object.")
    else:
        for scheme, value in identifiers.items():
            if scheme not in profile.identifier_schemes:
                errors.append(f"identifier scheme {scheme!r} is not declared in the {profile.name} profile.")
            if not _is_clean_text(value):
                errors.append(f"identifier {scheme!r} must be non-empty text.")
    return errors


def _is_clean_text(value: Any) -> bool:
    return isinstance(value, str) and bool(value) and value == " ".join(value.split())


def _is_iso_date(value: Any) -> bool:
    if not isinstance(value, str):
        return False
    try:
        datetime.date.fromisoformat(value)
    except ValueError:
        return False
    return len(value) == 10
